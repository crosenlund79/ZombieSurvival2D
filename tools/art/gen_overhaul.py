def _boot(c, x, y, w, h, flip=False):
    b = [(x, y), (x + w, y), (x + w + (6 if not flip else -6), y + h), (x - (2 if not flip else -2), y + h)]
    poly_fill(c, b, hexc("#2B231C"), tex=0.2, ink=1.8)
    c.ink([(x + 2, y + h * 0.55), (x + w, y + h * 0.55)], width=0.9, color=hexc("#5A4A3A"), alpha=200)


