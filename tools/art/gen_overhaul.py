    m = c.fill(bulge, SOIL, tex=0.3, cell=10, light=(-1, -1, 0.35))
    for k, y in enumerate(range(150, 400, 34)):  # strata bands
        pts = [(x, y + 7 * math.sin(x / 38.0 + k * 1.7)) for x in range(20, 345, 18)]
