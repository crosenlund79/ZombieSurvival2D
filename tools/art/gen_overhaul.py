def foliage(c, cx, cy, rx, ry, palette=(LEAF_D, LEAF, LEAF_M, LEAF_L), lobes=34, leaf_size=10, sun=(-0.7, -0.8)):
    """A tree crown built from overlapping leaf clumps: dark core, mid masses,
    sunlit clumps top-left, individual inked leaves on the rim, hatched shade."""
    dark, mid, mid2, light = palette
    core = c.blob(cx, cy + ry * 0.08, rx * 0.95, ry * 0.9, n=22, irregular=0.12)
    m = c.fill(core, mix(dark, INK, 0.25), tex=0.35, cell=8)
    clumps = []
    for i in range(lobes):
        a = c.rng.uniform(0, 6.283); r = c.rng.uniform(0.15, 1.0) ** 0.6
        x = cx + math.cos(a) * rx * r * 0.85; y = cy + math.sin(a) * ry * r * 0.82
        s = c.rng.uniform(0.2, 0.33)
        clumps.append((y, x, s))
    clumps.sort()
    for y, x, s in clumps:
        k = (x - cx) / rx * -sun[0] + (y - cy) / ry * -sun[1]   # >0 = toward the light
        col = light if k > 0.45 else (mid2 if k > 0.0 else (mid if k > -0.45 else dark))
        b = c.blob(x, y, rx * s, ry * s * 0.82, n=16, irregular=0.28)
        mm = c.fill(b, col, tex=0.3, cell=5, light=(sun[0], sun[1], 0.4))
        if k < 0.1:
            c.shade(mm, -sun[0], -sun[1], 3.5, 70)
        n = len(b)
        c.ink(b[int(n * 0.45):] + b[:int(n * 0.05)], width=1.5, alpha=175, seg=3)  # lower edge inked
    # rim leaves: individual leaves breaking the silhouette
    for _ in range(int(lobes * 3.2)):
        a = c.rng.uniform(0, 6.283)
        x = cx + math.cos(a) * rx * c.rng.uniform(0.82, 1.0)
        y = cy + math.sin(a) * ry * c.rng.uniform(0.8, 0.98)
        k = math.cos(a) * -sun[0] + math.sin(a) * -sun[1]
        col = light if k > 0.3 else (mid2 if k > -0.3 else mid)
        c.leaf(x, y, leaf_size * c.rng.uniform(0.7, 1.25), math.degrees(a) + c.rng.uniform(-50, 50), col)
    # sunlit flecks
    c.speckle(m, int(rx * ry / 70), mix(light, LEAF_Y, 0.5), size=(1.4, 3.2), alpha=(120, 210))


def bark_trunk(c, pts, col, lines=10, knots=2):
    m = poly_fill(c, pts, col, tex=0.4, cell=6, light=(-1, 0, 0.45), ink=2.8, shade=(1, 0, 4, 100))
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
    for _ in range(lines):
        x = c.rng.uniform(min(xs) + 6, max(xs) - 6); y0 = c.rng.uniform(min(ys), max(ys) - 30)
        c.ink([(x, y0), (x + c.rng.uniform(-4, 4), y0 + c.rng.uniform(20, 70))], width=c.rng.uniform(0.9, 1.6), alpha=150)
    for _ in range(knots):
        x = c.rng.uniform(min(xs) + 10, max(xs) - 10); y = c.rng.uniform(min(ys) + 30, max(ys) - 30)
        c.ink_poly(c.blob(x, y, 5, 8, n=10, irregular=0.2), width=1.4, alpha=200)
    c.moss(m, 0.35)
    return m


