def farmhouse():
    W, H = 880, 820
    c = Canvas(W, H, seed=2011)
    base = 790
    c.soft_shadow((50, base - 46, 870, base + 26), alpha=130, blur=14)
    fx0, fx1, ftop = 120, 760, 470
    fm = siding(c, fx0, fx1, ftop, base - 30, PAINT, board=20)
    c.grime(fm, 0.55, drips=True)
