def poly_fill(c, pts, col, tex=0.25, cell=10, light=(-1, -1, 0.3), ink=2.0, shade=None, alpha=235):
    m = c.fill(pts, col, tex=tex, cell=cell, light=light)
    if shade:
        c.shade(m, *shade)
    if ink:
        c.ink_poly(pts, width=ink, alpha=alpha)
    return m


def grass_blades(c, x0, x1, y, n, h=(10, 26), cols=None, lean=7):
    cols = cols or [MOSS_D, MOSS, LEAF_M, OLIVE, KHAKI]
    for _ in range(n):
        x = c.rng.uniform(x0, x1)
        hh = c.rng.uniform(*h)
        ln = c.rng.uniform(-lean, lean)
        col = c.rng.choice(cols)
        w = c.rng.uniform(1.4, 2.6)
        c.ink([(x, y), (x + ln * 0.4, y - hh * 0.55), (x + ln, y - hh)], width=w, color=col, wobble=0.25, seg=3)


def weeds(c, cx, by, w, h, n=14, flowers=0.0):
    grass_blades(c, cx - w / 2, cx + w / 2, by, n, (h * 0.35, h), lean=9)
    for _ in range(int(n * 0.25)):  # broad weed leaves
        x = cx + c.rng.uniform(-w / 2, w / 2)
        c.leaf(x, by - 2, c.rng.uniform(8, 14), c.rng.uniform(-150, -30), c.rng.choice([LEAF, LEAF_M, MOSS]))
    for _ in range(int(n * flowers)):
        x = cx + c.rng.uniform(-w / 2, w / 2); y = by - c.rng.uniform(h * 0.4, h)
        r = c.rng.uniform(1.8, 3.2)
        c.ellipse_fill((x - r, y - r, x + r, y + r), c.rng.choice(FLOWERS), tex=0.1)


