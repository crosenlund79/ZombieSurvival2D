    c.shade(c.mask([(fx0, ftop), (fx1, ftop), (fx1, ftop + 60), (fx0, ftop + 60)]), 0, -1, 5, 80, reach=1.0)
    c.ink_poly([(fx0, ftop), (fx1, ftop), (fx1, base - 30), (fx0, base - 30)], width=3.4)
    for x in (fx0 + 6, fx1 - 6):  # corner boards
        c.fill([(x - 7, ftop), (x + 7, ftop), (x + 7, base - 30), (x - 7, base - 30)], mix(PAINT, WOOD_L, 0.3), tex=0.3)
        c.ink_poly([(x - 7, ftop), (x + 7, ftop), (x + 7, base - 30), (x - 7, base - 30)], width=1.8)
    found = [(fx0 - 8, base - 34), (fx1 + 8, base - 34), (fx1 + 8, base), (fx0 - 8, base)]
    fdm = c.fill(found, STONE, tex=0.35, cell=8)
    x = fx0 - 6
    while x < fx1 + 6:  # fieldstones
        wst = c.rng.uniform(26, 46)
        for row in (0, 1):
            y = base - 33 + row * 17
            st = c.blob(x + wst / 2 + row * 10, y + 8, wst / 2 - 2, 7, n=10, irregular=0.15)
            c.fill(st, mix(STONE, STONE_L, c.rng.uniform(0, 0.5)), tex=0.3, cell=5)
            c.ink_poly(st, width=1.1, alpha=170)
        x += wst
    c.moss(fdm, 0.6)
    c.ink_poly(found, width=2.6)
    # roof: weathered slate with warm drift, sagging rows, broken patches showing battens
    rx0, rx1, rtop = 70, 810, 110
    roof = [(rx0 + 70, rtop), (rx1 - 70, rtop), (rx1, ftop + 20), (rx0, ftop + 20)]
    slate, slate_w = mix(SOOT, STONE, 0.42), mix(STONE, WOOD_G, 0.45)
    rm = c.fill(roof, slate, tex=0.25, cell=30, light=(-0.4, -0.8, 0.35))
    holes = [c.blob(c.rng.uniform(rx0 + 160, rx1 - 160), c.rng.uniform(rtop + 70, ftop - 40),
                    c.rng.uniform(22, 44), c.rng.uniform(14, 24), n=12, irregular=0.45) for _ in range(4)]
    hole_m = [c.mask(h) for h in holes]
    for i, y in enumerate(range(rtop + 18, ftop + 20, 20)):
        t = (y - rtop) / (ftop + 20 - rtop)
        xl = rx0 + 70 - 70 * t; xr = rx1 - 70 + 70 * t
        x = xl + 6 + (i % 2) * 13
        while x < xr - 8:
            sw = c.rng.uniform(22, 32)
            mid = (x + sw / 2 - W / 2) / (W / 2)
            sag = 7 * (1 - mid * mid) * t  # rows dip toward the middle (old, tired rafters)
            x2 = min(xr - 4, x + sw)
            sh = [(x, y - 19 + sag), (x2, y - 19 + sag), (x2, y + sag + c.rng.uniform(-1, 1)), (x, y + sag + c.rng.uniform(-1, 2))]
            v = c.rng.random()
            col = mix(slate, slate_w, c.rng.uniform(0, 0.45)) if v > 0.06 else mix(slate, RUST_D, 0.2)
            c.fill(sh, col, tex=0.22, cell=6)
            c.ink([(x, y + sag), (x2, y + sag)], width=1.4, alpha=190, seg=8)
            c.ink([(x, y - 19 + sag), (x + c.rng.uniform(-1, 1), y + sag)], width=0.9, alpha=120, seg=8)
            if c.rng.random() < 0.08:  # cracked slate
                c.ink([(x + 4, y - 16 + sag), (x + sw * 0.5, y - 8 + sag), (x + sw * 0.4, y - 2 + sag)], width=0.8, alpha=150)
            x += sw
    for hp in holes:  # broken patches: dark gap with battens and splintered slate edge
        hm = c.fill(hp, hexc("#1C1814"), tex=0.2)
        xs = [p[0] for p in hp]; ys = [p[1] for p in hp]
        for by in range(int(min(ys)) + 6, int(max(ys)), 11):
            bat = [(min(xs) - 2, by), (max(xs) + 2, by), (max(xs) + 2, by + 5), (min(xs) - 2, by + 5)]
            lm = c.mask(bat)
            c.fill(None, mix(WOOD_D, SOOT, 0.3), tex=0.3, mask=ImageChops.multiply(lm, hm))
        c.ink_poly(hp, width=2.0, alpha=220)
    for _ in range(7):  # moss carpets
        mx = c.rng.uniform(rx0 + 110, rx1 - 110); my = c.rng.uniform(rtop + 50, ftop + 5)
        moss_carpet(c, mx, my, c.rng.uniform(30, 70), c.rng.uniform(9, 18))
