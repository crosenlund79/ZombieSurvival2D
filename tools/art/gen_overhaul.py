def siding(c, x0, x1, y0, y1, col, board=20):
    """Weathered horizontal clapboards with per-board colour drift and gaps."""
    m = c.fill([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], col, tex=0.22, cell=30, light=(-0.6, -0.2, 0.25))
    y = y0
    while y < y1:
        drift = c.rng.uniform(-0.12, 0.1)
        bm = c.mask([(x0, y), (x1, y), (x1, min(y1, y + board)), (x0, min(y1, y + board))])
        c.fill(None, mix(col, PAINT_D if drift < 0 else STRAW, abs(drift)), tex=0.25, cell=20, mask=bm, light=(-0.6, -1, 0.2))
        c.ink([(x0 + 2, y + board - 1), (x1 - 2, y + board - 1 + c.rng.uniform(-1.2, 1.2))], width=1.3, alpha=150, wobble=0.6)
        if c.rng.random() < 0.25:  # peeled paint showing grey wood
            px = c.rng.uniform(x0 + 20, x1 - 80)
            c.fill(c.blob(px, y + board * 0.5, c.rng.uniform(14, 40), board * 0.32, n=10, irregular=0.4), WOOD_G, tex=0.3)
        y += board
    return m


