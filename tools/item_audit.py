#!/usr/bin/env python3
"""Iteration 014: writes docs/iterations/014_item_audit.md — every catalogue item with its
id, category, weight, stack limit, what it does and where it can be found or made
(loot pools, authored containers and finds, recipes, the world itself).
Usage: python3 tools/item_audit.py"""
import json, glob, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
items = json.load(open(os.path.join(ROOT, "content", "items.json")))
loc = json.load(open(os.path.join(ROOT, "locale", "strings.json")))
pools = json.load(open(os.path.join(ROOT, "content", "loot_pools.json")))
recipes = json.load(open(os.path.join(ROOT, "content", "recipes.json")))["recipes"]
WORLD = {"wood": "felling trees", "water_dirty": "rain collector", "water_clean": "water purifier", "potato": "hydroponic planter"}


def en(k):
    return loc.get(k, {}).get("en", k)


src = {i: [] for i in items["items"]}
for name, p in pools["pools"].items():
    for it in p["items"]:
        src[it].append("pool " + name)
for j in pools["junk"]:
    src[j].append("junk (any container)")
for rid, r in recipes.items():
    for o in r.get("out", {}):
        src[o].append("craft")
for f in sorted(glob.glob(os.path.join(ROOT, "content", "regions", "*.json"))):
    d = json.load(open(f))
    for e in d.get("entities", []):
        for key in ("loot", "items"):
            if isinstance(e.get(key), dict):
                for it in e[key]:
                    if it in src:
                        src[it].append("found at " + e["id"])
        if isinstance(e.get("gear"), list):
            for it in e["gear"]:
                if it in src:
                    src[it].append("found at " + e["id"])
for it, how in WORLD.items():
    src[it].append(how)


def does(i):
    v = items["items"][i]
    bits = []
    if v.get("use"):
        bits.append("use: " + v["use"])
    for k in ("food", "hydration", "heal", "health", "warmth", "insulation", "carry", "repair", "burn_seconds"):
        if k in v and not isinstance(v[k], dict):
            bits.append(f"{k} {v[k]}")
    if v.get("slot"):
        bits.append("slot " + v["slot"])
    if "firearm" in v:
        fa = v["firearm"]
        bits.append(f"firearm {fa['damage']} dmg, {fa['capacity']} rounds of {fa['ammo']}")
    elif "damage" in v and v.get("slot") == "hand":
        bits.append(f"melee {v['damage']} dmg")
    return ", ".join(bits) or "material / trade"


def short(sources):
    pools_ = sorted({s[5:] for s in sources if s.startswith("pool ")})
    other = sorted({s for s in sources if not s.startswith("pool ") and not s.startswith("found at ")})
    found = sorted({s[9:] for s in sources if s.startswith("found at ")})
    out = []
    if pools_:
        out.append("pools: " + ", ".join(pools_[:6]) + (f" (+{len(pools_) - 6})" if len(pools_) > 6 else ""))
    if found:
        out.append("found: " + ", ".join(found[:3]) + (f" (+{len(found) - 3})" if len(found) > 3 else ""))
    out += other
    return "; ".join(out) or "**none**"


cats = items.get("categories", {})
lines = ["# Iteration 014 — item audit", "",
         f"{len(items['items'])} items. Generated by `tools/item_audit.py` from `content/items.json`, `content/loot_pools.json`, "
         "`content/recipes.json` and the region files. Weight in kg (shown, not limiting); stack = units per carrying slot.", ""]
missing = [i for i, s in src.items() if not s]
lines.append(f"Items without any acquisition route: **{len(missing)}**" + (": " + ", ".join(missing) if missing else ""))
lines.append("")
for cat in cats:
    ids = [i for i, v in items["items"].items() if v.get("cat") == cat]
    if not ids:
        continue
    lines += [f"## {en(cats[cat])}", "", "| id | name | kg | stack | does | where |", "|---|---|---|---|---|---|"]
    for i in ids:
        v = items["items"][i]
        lines.append(f"| `{i}` | {en(v['name_key'])} | {v['weight']} | {v['stack_limit']} | {does(i)} | {short(src[i])} |")
    lines.append("")
with open(os.path.join(ROOT, "docs", "iterations", "014_item_audit.md"), "w") as f:
    f.write("\n".join(lines))
print("audited", len(items["items"]), "missing", len(missing))
